import AppKit
import Foundation

/// 剪贴板机密与瞬时内容过滤策略
struct PasteboardContentFilter: Sendable {
    /// 敏感与机密数据类型标识
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.apple.password",
        "com.apple.securetext",
        "com.agilebits.onepassword", // 1Password
        "com.lastpass.mac", // LastPass
        "com.dashlane.dashlanephonefinal", // Dashlane
        "com.keeper.KeeperPassManager", // Keeper
        "io.enpass.Enpass", // Enpass
        "com.bitwarden.desktop", // Bitwarden
    ]

    /// 瞬时与临时数据类型标识（TextExpander、自动化宏、临时粘贴板等）
    static let ephemeralTypes: Set<String> = [
        "org.nspasteboard.TransientType", // 瞬时内容标准标识
        "org.nspasteboard.AutoGeneratedType", // 自动生成内容
        "org.nspasteboard.RestoredType", // 恢复的内容
        "de.petermaurer.TransientPasteboardType", // TextExpander/Butler
        "com.typeit4me.clipping", // TypeIt4Me
        "com.apple.pasteboard.promised-file-content-type",
    ]

    /// 主流密码管理软件与系统凭证工具 Bundle ID（全小写）
    static let passwordManagerBundleIDs: Set<String> = [
        "com.agilebits.onepassword",
        "com.agilebits.onepassword7",
        "com.1password.1password",
        "com.1password.onepassword",
        "com.bitwarden.desktop",
        "org.keepassxc.keepassxc",
        "app.macpass.macpass",
        "com.enpass.enpass",
        "io.enpass.enpass",
        "com.nordpass.macos",
        "com.lastpass.mac",
        "com.lastpass.lastpass",
        "com.dashlane.dashlanephonefinal",
        "com.dashlane.dashlane",
        "com.keepersecurity.keeperpasswordmanager",
        "com.keeper.keeperpassmanager",
        "com.apple.keychainaccess",
        "com.apple.passwords",
    ]

    /// 检查应用 Bundle ID 是否为已知密码管理器或凭证工具
    static func isPasswordManager(bundleID: String?) -> Bool {
        guard let bundleID = bundleID?.trimmingCharacters(in: .whitespacesAndNewlines), !bundleID.isEmpty else {
            return false
        }
        return passwordManagerBundleIDs.contains(bundleID.lowercased())
    }

    // MARK: - 敏感凭证高危正则表达式规则

    private static let privateKeyRegex: NSRegularExpression? = {
        try? NSRegularExpression(
            pattern: "-----BEGIN (?:[A-Z0-9_-]+ )?PRIVATE KEY-----",
            options: []
        )
    }()

    private static let awsKeyRegex: NSRegularExpression? = {
        try? NSRegularExpression(
            pattern: "\\bAKIA[0-9A-Z]{16}\\b",
            options: []
        )
    }()

    private static let githubTokenRegex: NSRegularExpression? = {
        try? NSRegularExpression(
            pattern: "\\b(?:ghp|gho|ghu|ghs|ghr)_[A-Za-z0-9_]{36,255}\\b",
            options: []
        )
    }()

    /// 检查纯文本内容是否命中高危敏感凭证特征（如私钥、API 令牌等）
    /// - Parameter text: 待检测的文本字符串
    /// - Returns: 若包含高危凭证，返回敏感类型描述；否则返回 nil
    static func detectSensitiveCredential(in text: String) -> String? {
        guard !text.isEmpty else { return nil }

        // 私钥特征通常在开头或前几千字符内，快速前缀检查（避免数兆大文本做全量正则匹配）
        let checkSlice: Substring = text.count > 32768 ? text.prefix(32768) : text[...]
        let checkString = String(checkSlice)
        let fullRange = NSRange(checkString.startIndex ..< checkString.endIndex, in: checkString)

        if let regex = privateKeyRegex, regex.firstMatch(in: checkString, options: [], range: fullRange) != nil {
            return "私钥凭证 (PRIVATE KEY)"
        }
        if let regex = awsKeyRegex, regex.firstMatch(in: checkString, options: [], range: fullRange) != nil {
            return "AWS Access Key 访问凭证"
        }
        if let regex = githubTokenRegex, regex.firstMatch(in: checkString, options: [], range: fullRange) != nil {
            return "GitHub Personal Access Token"
        }
        return nil
    }

    /// 检查类型列表是否命中机密或瞬时内容规则
    /// - Returns: 若需要忽略，返回具体的拦截原因；若正常放行，返回 nil
    static func shouldIgnoreContent(
        types: [NSPasteboard.PasteboardType],
        checkSensitive: Bool,
        checkEphemeral: Bool
    ) -> String? {
        for type in types {
            let rawType = type.rawValue
            if checkSensitive, sensitiveTypes.contains(rawType) {
                return "机密内容: \(rawType)"
            }
            if checkEphemeral, ephemeralTypes.contains(rawType) {
                return "瞬时内容: \(rawType)"
            }
        }
        return nil
    }
}

/// 自适应后台轮询降频与时钟状态机
struct AdaptiveIntervalPolicy: Sendable {
    /// 活跃状态巡检间隔（120ms）
    static let activeInterval: DispatchTimeInterval = .milliseconds(120)
    /// 空闲状态巡检间隔（1200ms）
    static let idleInterval: DispatchTimeInterval = .milliseconds(1200)
    /// 空闲步进阈值（10次未变动后降频）
    static let idleThresholdTicks = 10

    /// 计算下一次是否应当保持活跃模式
    /// - Parameters:
    ///   - countChanged: 本次巡检是否发生了 count 变动
    ///   - currentIdleTicks: 当前已连续未变动的次数
    /// - Returns: (是否活跃, 新的 idleTicks)
    static func nextTick(
        countChanged: Bool,
        currentIdleTicks: Int
    ) -> (isActive: Bool, nextIdleTicks: Int) {
        if countChanged {
            return (isActive: true, nextIdleTicks: 0)
        } else {
            let nextTicks = currentIdleTicks + 1
            let isActive = nextTicks < idleThresholdTicks
            return (isActive: isActive, nextIdleTicks: nextTicks)
        }
    }
}
