//
//  PasteboardMonitoringTests.swift
//  Tests
//
//  Unit tests for Pasteboard filtering, transient content checks, and utilities.
//

import AppKit
import Foundation

@MainActor
final class PasteboardMonitoringTests {
    static func run(runner: TestRunner.Type) {
        print("\n--- Testing Pasteboard Monitoring & Ephemeral Content Filtering ---")

        testEphemeralContentFiltering(runner: runner)
        testSensitiveContentFiltering(runner: runner)
        testNormalContentPassthrough(runner: runner)
        testMixedTypesFiltering(runner: runner)
        testAdaptiveIntervalPolicy(runner: runner)

        print("✓ Pasteboard Monitoring & Ephemeral Content tests passed!")
    }

    private static func testEphemeralContentFiltering(runner: TestRunner.Type) {
        let transientType = NSPasteboard.PasteboardType("org.nspasteboard.TransientType")
        let autoGeneratedType = NSPasteboard.PasteboardType("org.nspasteboard.AutoGeneratedType")
        let textExpanderType = NSPasteboard.PasteboardType("de.petermaurer.TransientPasteboardType")

        // 1. When checkEphemeral is true, transient content must be detected and filtered
        let result1 = PasteboardContentFilter.shouldIgnoreContent(
            types: [transientType, .string],
            checkSensitive: false,
            checkEphemeral: true
        )
        runner.assertTrue(result1 != nil, "Transient content must be ignored when checkEphemeral is enabled")
        runner.assertTrue(result1?.contains("瞬时内容") == true, "Ignore reason should indicate transient content")

        let result2 = PasteboardContentFilter.shouldIgnoreContent(
            types: [autoGeneratedType],
            checkSensitive: false,
            checkEphemeral: true
        )
        runner.assertTrue(result2 != nil, "Auto-generated content must be ignored")

        let result3 = PasteboardContentFilter.shouldIgnoreContent(
            types: [textExpanderType],
            checkSensitive: false,
            checkEphemeral: true
        )
        runner.assertTrue(result3 != nil, "TextExpander transient type must be ignored")

        // 2. When checkEphemeral is false, transient content is allowed through
        let result4 = PasteboardContentFilter.shouldIgnoreContent(
            types: [transientType],
            checkSensitive: false,
            checkEphemeral: false
        )
        runner.assertEqual(result4, nil, "Transient content should not be ignored if checkEphemeral is disabled")
    }

    private static func testSensitiveContentFiltering(runner: TestRunner.Type) {
        let onePasswordType = NSPasteboard.PasteboardType("com.agilebits.onepassword")
        let bitwardenType = NSPasteboard.PasteboardType("com.bitwarden.desktop")
        let applePasswordType = NSPasteboard.PasteboardType("com.apple.password")

        // Sensitive enabled
        let result1 = PasteboardContentFilter.shouldIgnoreContent(
            types: [onePasswordType, .string],
            checkSensitive: true,
            checkEphemeral: false
        )
        runner.assertTrue(result1 != nil, "1Password type must be ignored when checkSensitive is true")
        runner.assertTrue(result1?.contains("机密内容") == true, "Ignore reason should indicate sensitive content")

        let result2 = PasteboardContentFilter.shouldIgnoreContent(
            types: [bitwardenType],
            checkSensitive: true,
            checkEphemeral: false
        )
        runner.assertTrue(result2 != nil, "Bitwarden type must be ignored")

        let result3 = PasteboardContentFilter.shouldIgnoreContent(
            types: [applePasswordType],
            checkSensitive: true,
            checkEphemeral: false
        )
        runner.assertTrue(result3 != nil, "Apple password type must be ignored")

        // Sensitive disabled
        let result4 = PasteboardContentFilter.shouldIgnoreContent(
            types: [onePasswordType],
            checkSensitive: false,
            checkEphemeral: false
        )
        runner.assertEqual(result4, nil, "Sensitive content should pass if checkSensitive is false")
    }

    private static func testNormalContentPassthrough(runner: TestRunner.Type) {
        let normalTypes: [NSPasteboard.PasteboardType] = [
            .string,
            .rtf,
            .html,
            .png,
            .tiff,
            .fileURL,
        ]

        let result = PasteboardContentFilter.shouldIgnoreContent(
            types: normalTypes,
            checkSensitive: true,
            checkEphemeral: true
        )
        runner.assertEqual(result, nil, "Standard clipboard types must never be ignored")
    }

    private static func testMixedTypesFiltering(runner: TestRunner.Type) {
        // Office/Browser copy: contains both rich text and a transient tag
        let mixedTypes: [NSPasteboard.PasteboardType] = [
            .string,
            .rtf,
            .html,
            NSPasteboard.PasteboardType("org.nspasteboard.TransientType"),
        ]

        let result = PasteboardContentFilter.shouldIgnoreContent(
            types: mixedTypes,
            checkSensitive: true,
            checkEphemeral: true
        )
        runner.assertTrue(result != nil, "Any transient tag present in mixed types must trigger ignore")
    }

    private static func testAdaptiveIntervalPolicy(runner: TestRunner.Type) {
        // 1. Initial active state with count changes remains active
        let tick1 = AdaptiveIntervalPolicy.nextTick(countChanged: true, currentIdleTicks: 0)
        runner.assertTrue(tick1.isActive, "Should be active when count changes")
        runner.assertEqual(tick1.nextIdleTicks, 0, "Idle ticks reset to 0")

        // 2. Incremental idle ticks under threshold (e.g. 5 ticks) remain active
        let tick2 = AdaptiveIntervalPolicy.nextTick(countChanged: false, currentIdleTicks: 5)
        runner.assertTrue(tick2.isActive, "Under threshold (6 < 10) should remain active")
        runner.assertEqual(tick2.nextIdleTicks, 6, "Idle ticks increment to 6")

        // 3. Reaching threshold (10 ticks) switches to idle mode (isActive = false)
        let tick3 = AdaptiveIntervalPolicy.nextTick(countChanged: false, currentIdleTicks: 9)
        runner.assertTrue(!tick3.isActive, "Reaching threshold (10 >= 10) switches to idle")
        runner.assertEqual(tick3.nextIdleTicks, 10, "Idle ticks reaches 10")

        // 4. Any new change immediately wakes up to active mode
        let tick4 = AdaptiveIntervalPolicy.nextTick(countChanged: true, currentIdleTicks: 10)
        runner.assertTrue(tick4.isActive, "New change wakes up to active mode")
        runner.assertEqual(tick4.nextIdleTicks, 0, "Idle ticks reset to 0")
    }
}
