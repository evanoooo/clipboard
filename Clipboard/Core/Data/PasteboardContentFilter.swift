import AppKit
import Foundation

/// 剪贴板机密与瞬时内容过滤策略
struct PasteboardContentFilter: Sendable {
    /// 敏感与机密数据类型标识
    static let sensitiveTypes: Set<String> = [
        "org.nspasteboard.ConcealedType",
        "com.apple.password",
        "com.apple.securetext",
        "com.agilebits.onepassword", // 1Password
        "com.lastpass.mac", // LastPass
        "com.dashlane.dashlanephonefinal", // Dashlane
        "com.keeper.KeeperPassManager", // Keeper
        "io.enpass.Enpass", // Enpass
        "com.bitwarden.desktop", // Bitwarden
    ]

    /// 瞬时与临时数据类型标识（TextExpander、自动化宏、临时粘贴板等）
    static let ephemeralTypes: Set<String> = [
        "org.nspasteboard.TransientType", // 瞬时内容标准标识
        "org.nspasteboard.AutoGeneratedType", // 自动生成内容
        "org.nspasteboard.RestoredType", // 恢复的内容
        "de.petermaurer.TransientPasteboardType", // TextExpander/Butler
        "com.typeit4me.clipping", // TypeIt4Me
        "com.apple.pasteboard.promised-file-content-type",
    ]

    /// 检查类型列表是否命中机密或瞬时内容规则
    /// - Returns: 若需要忽略，返回具体的拦截原因；若正常放行，返回 nil
    static func shouldIgnoreContent(
        types: [NSPasteboard.PasteboardType],
        checkSensitive: Bool,
        checkEphemeral: Bool
    ) -> String? {
        for type in types {
            let rawType = type.rawValue
            if checkSensitive, sensitiveTypes.contains(rawType) {
                return "机密内容: \(rawType)"
            }
            if checkEphemeral, ephemeralTypes.contains(rawType) {
                return "瞬时内容: \(rawType)"
            }
        }
        return nil
    }
}

/// 自适应后台轮询降频与时钟状态机
struct AdaptiveIntervalPolicy: Sendable {
    /// 活跃状态巡检间隔（120ms）
    static let activeInterval: DispatchTimeInterval = .milliseconds(120)
    /// 空闲状态巡检间隔（1200ms）
    static let idleInterval: DispatchTimeInterval = .milliseconds(1200)
    /// 空闲步进阈值（10次未变动后降频）
    static let idleThresholdTicks = 10

    /// 计算下一次是否应当保持活跃模式
    /// - Parameters:
    ///   - countChanged: 本次巡检是否发生了 count 变动
    ///   - currentIdleTicks: 当前已连续未变动的次数
    /// - Returns: (是否活跃, 新的 idleTicks)
    static func nextTick(
        countChanged: Bool,
        currentIdleTicks: Int
    ) -> (isActive: Bool, nextIdleTicks: Int) {
        if countChanged {
            return (isActive: true, nextIdleTicks: 0)
        } else {
            let nextTicks = currentIdleTicks + 1
            let isActive = nextTicks < idleThresholdTicks
            return (isActive: isActive, nextIdleTicks: nextTicks)
        }
    }
}
